package com.vcet.transport.service;

import com.vcet.transport.model.Booking;
import com.vcet.transport.model.BookingStatus;
import com.vcet.transport.model.Schedule;
import com.vcet.transport.repository.BookingRepository;
import com.vcet.transport.repository.ScheduleRepository;
import org.springframework.stereotype.Service;

import java.util.*;
import java.util.stream.Collectors;

/**
 * Service for calculating route-wise revenue, fleet occupancy, and travel manifests.
 * Utilizes Java Streams, Lambdas, and Collections API (Unit 5: 25ITT32).
 */
@Service
public class ReportService {

    private final BookingRepository bookingRepository;
    private final ScheduleRepository scheduleRepository;

    public ReportService(BookingRepository bookingRepository, ScheduleRepository scheduleRepository) {
        this.bookingRepository = bookingRepository;
        this.scheduleRepository = scheduleRepository;
    }

    /**
     * Aggregates total revenue generated by each transit corridor using Java Streams.
     */
    public List<Map<String, Object>> getRouteWiseRevenue() {
        List<Booking> confirmedBookings = bookingRepository.findAll().stream()
                .filter(b -> b.getStatus() == BookingStatus.CONFIRMED)
                .collect(Collectors.toList());

        Map<String, Double> revenueByRoute = confirmedBookings.stream()
                .collect(Collectors.groupingBy(
                        b -> b.getSchedule().getRoute().getRouteSummary(),
                        Collectors.summingDouble(Booking::getTotalAmount)
                ));

        Map<String, Long> bookingsByRoute = confirmedBookings.stream()
                .collect(Collectors.groupingBy(
                        b -> b.getSchedule().getRoute().getRouteSummary(),
                        Collectors.counting()
                ));

        List<Map<String, Object>> result = new ArrayList<>();
        revenueByRoute.forEach((route, rev) -> {
            Map<String, Object> map = new HashMap<>();
            map.put("route", route);
            map.put("totalRevenue", rev);
            map.put("bookingCount", bookingsByRoute.getOrDefault(route, 0L));
            result.add(map);
        });

        // Sort descending by revenue
        result.sort((a, b) -> Double.compare((Double) b.get("totalRevenue"), (Double) a.get("totalRevenue")));
        return result;
    }

    /**
     * Computes seat occupancy rate per scheduled bus trip.
     */
    public List<Map<String, Object>> getScheduleOccupancy() {
        List<Schedule> schedules = scheduleRepository.findAll();
        List<Map<String, Object>> list = new ArrayList<>();

        for (Schedule s : schedules) {
            int capacity = s.getBus().getCapacity();
            int booked = capacity - s.getAvailableSeats();
            double occupancyPct = capacity > 0 ? ((double) booked / capacity) * 100.0 : 0.0;

            Map<String, Object> map = new HashMap<>();
            map.put("scheduleId", s.getId());
            map.put("busNumber", s.getBus().getBusNumber());
            map.put("busType", s.getBus().getBusType().getDisplayName());
            map.put("corridor", s.getRoute().getSourceCity() + " -> " + s.getRoute().getDestinationCity());
            map.put("travelDate", s.getTravelDate().toString());
            map.put("departureTime", s.getDepartureTime().toString());
            map.put("capacity", capacity);
            map.put("bookedSeats", booked);
            map.put("availableSeats", s.getAvailableSeats());
            map.put("occupancyPercentage", Math.round(occupancyPct * 100.0) / 100.0);
            list.add(map);
        }

        list.sort((a, b) -> Double.compare((Double) b.get("occupancyPercentage"), (Double) a.get("occupancyPercentage")));
        return list;
    }

    /**
     * Overall KPI metrics for top summary cards.
     */
    public Map<String, Object> getOverallSummary() {
        List<Booking> allBookings = bookingRepository.findAll();
        long confirmed = allBookings.stream().filter(b -> b.getStatus() == BookingStatus.CONFIRMED).count();
        long cancelled = allBookings.stream().filter(b -> b.getStatus() == BookingStatus.CANCELLED).count();
        double totalRevenue = allBookings.stream()
                .filter(b -> b.getStatus() == BookingStatus.CONFIRMED)
                .mapToDouble(Booking::getTotalAmount)
                .sum();

        List<Schedule> schedules = scheduleRepository.findAll();
        double avgOccupancy = schedules.stream()
                .mapToDouble(s -> {
                    int cap = s.getBus().getCapacity();
                    return cap > 0 ? ((double) (cap - s.getAvailableSeats()) / cap) * 100.0 : 0.0;
                })
                .average()
                .orElse(0.0);

        Map<String, Object> summary = new HashMap<>();
        summary.put("totalBookings", allBookings.size());
        summary.put("confirmedBookings", confirmed);
        summary.put("cancelledBookings", cancelled);
        summary.put("totalRevenue", Math.round(totalRevenue * 100.0) / 100.0);
        summary.put("averageOccupancyRate", Math.round(avgOccupancy * 10.0) / 10.0);
        summary.put("activeSchedulesCount", schedules.size());
        return summary;
    }

    /**
     * Real-time dynamic chart data for live interactive visualization.
     * Updates automatically whenever tickets are booked or cancelled.
     */
    public Map<String, Object> getLiveChartData() {
        List<Booking> allBookings = bookingRepository.findAll();
        List<Schedule> allSchedules = scheduleRepository.findAll();

        // 1. Route Demand & Revenue
        Map<String, Double> revByRoute = new LinkedHashMap<>();
        Map<String, Integer> seatsByRoute = new LinkedHashMap<>();

        for (Booking b : allBookings) {
            if (b.getStatus() == BookingStatus.CONFIRMED) {
                String rName = b.getSchedule().getRoute().getSourceCity() + " -> " + b.getSchedule().getRoute().getDestinationCity();
                revByRoute.put(rName, revByRoute.getOrDefault(rName, 0.0) + b.getTotalAmount());
                seatsByRoute.put(rName, seatsByRoute.getOrDefault(rName, 0) + b.getTickets().size());
            }
        }

        // 2. Bus Type Occupancy
        Map<String, List<Double>> occByBusType = new HashMap<>();
        for (Schedule s : allSchedules) {
            String bType = s.getBus().getBusType().name();
            int cap = s.getBus().getCapacity();
            double pct = cap > 0 ? ((double) (cap - s.getAvailableSeats()) / cap) * 100.0 : 0.0;
            occByBusType.computeIfAbsent(bType, k -> new ArrayList<>()).add(pct);
        }

        Map<String, Double> avgOccByType = new LinkedHashMap<>();
        occByBusType.forEach((type, list) -> {
            double avg = list.stream().mapToDouble(Double::doubleValue).average().orElse(0.0);
            avgOccByType.put(type, Math.round(avg * 10.0) / 10.0);
        });

        // 3. Booking Status counts
        long confirmedCount = allBookings.stream().filter(b -> b.getStatus() == BookingStatus.CONFIRMED).count();
        long cancelledCount = allBookings.stream().filter(b -> b.getStatus() == BookingStatus.CANCELLED).count();

        // 4. Daily booking trend
        Map<String, Long> dailyTrend = allBookings.stream()
                .filter(b -> b.getStatus() == BookingStatus.CONFIRMED)
                .collect(Collectors.groupingBy(
                        b -> b.getBookingTime().toLocalDate().toString(),
                        TreeMap::new,
                        Collectors.counting()
                ));

        Map<String, Object> chartData = new HashMap<>();
        chartData.put("routeLabels", new ArrayList<>(seatsByRoute.keySet()));
        chartData.put("routeDemandData", new ArrayList<>(seatsByRoute.values()));
        chartData.put("routeRevenueData", new ArrayList<>(revByRoute.values()));
        chartData.put("busTypeLabels", new ArrayList<>(avgOccByType.keySet()));
        chartData.put("busTypeOccupancyData", new ArrayList<>(avgOccByType.values()));
        chartData.put("statusLabels", Arrays.asList("Confirmed", "Cancelled"));
        chartData.put("statusData", Arrays.asList(confirmedCount, cancelledCount));
        chartData.put("dailyLabels", new ArrayList<>(dailyTrend.keySet()));
        chartData.put("dailyData", new ArrayList<>(dailyTrend.values()));

        return chartData;
    }
}
